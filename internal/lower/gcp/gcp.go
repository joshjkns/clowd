// Package gcp lowers a checked program to Google Cloud resources for the
// hashicorp/google provider.
//
// Each Clowd kind becomes a small set of resources:
//
//	service        Cloud Run service with its own service account
//	database       Cloud SQL instance on a private IP, its database and
//	               user, and the password in Secret Manager
//	bucket         Cloud Storage bucket
//	queue          Pub/Sub topic and the subscription its readers pull
//	load balancer  Application Load Balancer (global when public, regional
//	               when internal) with a serverless endpoint group per
//	               service and, for TLS, a Certificate Manager certificate
//	               validated by DNS
//
// Relationships add the wiring: IAM bindings for the service's account,
// environment variables and, for a database, a route into the network.
// The APIs the resources need are enabled in the project first.
//
// Like lower/aws, lowering trusts its input: the program has passed check
// and the capability matrix says it is deployable to GCP. The diagnostics
// it returns are about how a valid program maps onto Google Cloud (a CPU
// size Cloud Run doesn't offer, an override key the resource doesn't
// have).
package gcp

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"slices"
	"strings"

	"github.com/joshjkns/clowd/internal/diag"
	"github.com/joshjkns/clowd/internal/emit/tfjson"
	"github.com/joshjkns/clowd/internal/ir"
)

// Providers every GCP build may use: google for the resources, random for
// generated names and the database password.
const (
	ProviderSource       = "hashicorp/google"
	ProviderConstraint   = "~> 8.0"
	RandomSource         = "hashicorp/random"
	RandomConstraint     = "~> 3.7"
	providerName, random = "google", "random"
)

// Options are the deploy settings that aren't part of the program.
type Options struct {
	// Project prefixes every physical name, so projects can share a
	// Google Cloud project. It is the program's project name, or the
	// default the CLI picks when the program has none.
	Project string
	// Source is the .clowd file's name, for the generated file's header.
	Source string
	// ProviderVersions pin providers by local name ("google": "8.7.0");
	// a provider missing here uses its constraint.
	ProviderVersions map[string]string
}

// Result is a lowered program.
type Result struct {
	Config *tfjson.Config
	Diags  diag.List
}

// Lower turns p into Google Cloud resources.
func Lower(p *ir.Program, opts Options) *Result {
	l := &lowerer{p: p, opts: opts, cfg: &tfjson.Config{}, backends: map[string][]string{}}
	l.region()
	l.checkNames()
	if l.needsNetwork() {
		l.network()
	}
	for _, r := range p.Resources {
		switch r := r.(type) {
		case *ir.Service:
			l.service(r)
		case *ir.Database:
			l.database(r)
		case *ir.Bucket:
			l.bucket(r)
		case *ir.Queue:
			l.queue(r)
		case *ir.LoadBalancer:
			l.loadBalancer(r)
		}
	}
	l.overrides()
	l.apis()
	l.providers()
	l.checkAddresses()
	l.diags.Sort()
	return &Result{Config: l.cfg, Diags: l.diags}
}

type lowerer struct {
	p     *ir.Program
	opts  Options
	cfg   *tfjson.Config
	diags diag.List
	// loc is the region: a literal from the `use` line, or the provider's
	// region from the environment.
	loc any
	net network
	// backends are the backend services of each load balancer, by name.
	backends map[string][]string
	// usesRandom records whether a random_* resource was generated.
	usesRandom bool
}

func (l *lowerer) region() {
	for _, t := range l.p.Targets {
		if t.Cloud == ir.GCP && t.Region != "" {
			l.loc = t.Region
			return
		}
	}
	l.cfg.DataSource("google_client_config", "current", tfjson.Body{})
	l.loc = tfjson.Ref("data.google_client_config.current.region")
}

// providers declares the providers the configuration uses. The project's
// tags become labels on every resource through the provider's default
// labels, next to the one that marks what Clowd made.
func (l *lowerer) providers() {
	conf := tfjson.Body{"default_labels": l.labels()}
	if s, ok := l.loc.(string); ok {
		conf["region"] = s
	}
	if id := l.p.AccountOn(ir.GCP); id != "" {
		conf["project"] = id
	}
	version := func(name, constraint string) string {
		if v := l.opts.ProviderVersions[name]; v != "" {
			return "= " + v
		}
		return constraint
	}
	l.cfg.Providers = []tfjson.Provider{{Name: providerName, Source: ProviderSource, Version: version(providerName, ProviderConstraint), Config: conf}}
	if l.usesRandom {
		l.cfg.Providers = append(l.cfg.Providers, tfjson.Provider{Name: random, Source: RandomSource, Version: version(random, RandomConstraint)})
	}
	l.cfg.Comment = fmt.Sprintf("Generated by clowd from %s. Edit that file instead: this one is rewritten on every build.", l.opts.Source)
}

// labels are the project's labels. Label keys can't hold `:`, so Clowd's
// own is `clowd-project`.
func (l *lowerer) labels() map[string]string {
	labels := map[string]string{"clowd-project": l.opts.Project}
	for _, t := range l.p.Project.Tags {
		labels[t.Key] = t.Value
	}
	return labels
}

func (l *lowerer) has(k ir.Kind) bool {
	return slices.ContainsFunc(l.p.Resources, func(r ir.Resource) bool { return r.Kind() == k })
}

// needsNetwork reports whether anything is placed in a VPC: databases
// have private addresses, internal load balancers live in one, and
// services of a private network send everything through it.
func (l *lowerer) needsNetwork() bool {
	return l.has(ir.DatabaseKind) || l.p.Network.Private && l.has(ir.ServiceKind) || hasInternalLB(l.p)
}

// id is a resource's local name in the generated configuration.
func id(name string) string { return strings.ToLower(name) }

// physical returns a name for Google Cloud: the project and parts joined
// by dashes, lowercase, with underscores turned into dashes, which is
// what every resource accepts. A name longer than max is cut and given a
// short hash of the full name, so it stays unique.
func (l *lowerer) physical(max int, parts ...string) string {
	name := strings.ReplaceAll(strings.ToLower(strings.Join(append([]string{l.opts.Project}, parts...), "-")), "_", "-")
	if len(name) <= max {
		return name
	}
	sum := sha256.Sum256([]byte(name))
	suffix := hex.EncodeToString(sum[:])[:6]
	return strings.TrimRight(name[:max-len(suffix)-1], "-") + "-" + suffix
}

// suffixed is a physical name that ends in a generated suffix, for names
// that are global (buckets) or can't be reused soon after a delete
// (Cloud SQL instances): `<name>-<hex>`, at most max characters.
func (l *lowerer) suffixed(max int, n string, bytes int) tfjson.Expr {
	l.usesRandom = true
	suffix := l.cfg.Resource("random_id", n, tfjson.Body{"byte_length": bytes})
	return tfjson.Expr(tfjson.Escape(l.physical(max-2*bytes-1, n)) + "-${" + suffix + ".hex}")
}

// envPrefix is the prefix of the environment variables a relationship to
// name sets: `db` → DB_HOST, `user-files` → USER_FILES_BUCKET.
func envPrefix(name string) string {
	return strings.ToUpper(strings.ReplaceAll(name, "-", "_"))
}

// checkNames reports resources whose names differ only in `-` versus `_`,
// which Google Cloud would see as the same name.
func (l *lowerer) checkNames() {
	seen := map[string]ir.Resource{}
	for _, r := range l.p.Resources {
		h := r.Meta()
		key := strings.ReplaceAll(id(h.Name), "_", "-")
		if prev, ok := seen[key]; ok {
			l.diags.Add(diag.Errorf(h.Pos, "`%s` and `%s` get the same name on gcp, which allows only dashes", prev.Meta().Name, h.Name).
				Suggest("rename one of them"))
			continue
		}
		seen[key] = r
	}
}

// checkAddresses guards against two generated resources sharing an
// address, which contrived names (`web` and `web_80`) could cause.
func (l *lowerer) checkAddresses() {
	seen := map[string]bool{}
	for _, b := range l.cfg.Resources {
		if seen[b.Addr()] {
			l.diags.Add(diag.Errorf(diag.Span{}, "two generated gcp resources are both called `%s`", b.Addr()).
				Suggest("rename the resource whose name starts with `%s`", b.Name))
		}
		seen[b.Addr()] = true
	}
}

// ref is shorthand for tfjson.Ref of an attribute of addr.
func ref(addr, attr string) tfjson.Expr { return tfjson.Ref(addr + "." + attr) }

// member is the IAM member for a service account.
func member(account string) tfjson.Expr {
	return tfjson.Expr("serviceAccount:${" + account + ".email}")
}

// apiPrefixes map resource types to the API that serves them.
var apiPrefixes = []struct{ prefix, api string }{
	{"google_cloud_run_", "run.googleapis.com"},
	{"google_compute_", "compute.googleapis.com"},
	{"google_service_networking_", "servicenetworking.googleapis.com"},
	{"google_sql_", "sqladmin.googleapis.com"},
	{"google_secret_manager_", "secretmanager.googleapis.com"},
	{"google_pubsub_", "pubsub.googleapis.com"},
	{"google_storage_", "storage.googleapis.com"},
	{"google_certificate_manager_", "certificatemanager.googleapis.com"},
	{"google_service_account", "iam.googleapis.com"},
	{"google_artifact_registry_", "artifactregistry.googleapis.com"},
}

// apis enables the APIs the configuration's resources need, so it
// deploys to a new project, and makes each resource wait for its API.
// They stay enabled after `clowd destroy`: other things in the project
// may use them, and disabling an API can take minutes.
func (l *lowerer) apis() {
	var services []tfjson.Block
	enabled := map[string]string{}
	for i, b := range l.cfg.Resources {
		j := slices.IndexFunc(apiPrefixes, func(a struct{ prefix, api string }) bool { return strings.HasPrefix(b.Type, a.prefix) })
		if j < 0 {
			continue
		}
		api := apiPrefixes[j].api
		addr, ok := enabled[api]
		if !ok {
			name := strings.TrimSuffix(api, ".googleapis.com")
			services = append(services, tfjson.Block{Type: "google_project_service", Name: name, Body: tfjson.Body{
				"service":            api,
				"disable_on_destroy": false,
			}})
			addr = "google_project_service." + name
			enabled[api] = addr
		}
		deps, _ := b.Body["depends_on"].([]string)
		l.cfg.Resources[i].Body["depends_on"] = append(deps, addr)
	}
	l.cfg.Resources = append(services, l.cfg.Resources...)
}
