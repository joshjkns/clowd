// Package aws lowers a checked program to AWS resources for the
// hashicorp/aws provider.
//
// Each Clowd kind becomes a small set of resources:
//
//	service        ECS Fargate service, task definition, log group, IAM
//	               roles, security group, and autoscaling for a range
//	database       RDS instance with a managed master password, subnet
//	               group, security group
//	bucket         S3 bucket with its public access block
//	queue          SQS queue
//	load balancer  ALB, security group, listeners, target groups and, for
//	               TLS, an ACM certificate validated by DNS
//
// Relationships add the wiring: security group rules, IAM policy
// statements and environment variables. Services get a cluster and a
// network shared by the whole program.
//
// Lowering trusts its input: the program has passed check and the
// capability matrix says it is deployable to AWS, so anything the matrix
// marks unavailable is skipped rather than reported again. The diagnostics
// it returns are about how a valid program maps onto AWS (a Fargate size
// that had to be rounded up, an override key AWS doesn't have).
package aws

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"slices"
	"strings"

	"github.com/joshjkns/clowd/internal/diag"
	"github.com/joshjkns/clowd/internal/emit/tfjson"
	"github.com/joshjkns/clowd/internal/ir"
)

// ProviderSource is the provider every AWS build uses.
const ProviderSource = "hashicorp/aws"

// ProviderConstraint is the version constraint used until clowd.lock pins
// a version.
const ProviderConstraint = "~> 6.0"

// Options are the deploy settings that aren't part of the program.
type Options struct {
	// Project prefixes every physical name, so projects can share an
	// account. It is the program's project name, or the default the CLI
	// picks when the program has none (see check.ValidProjectName).
	Project string
	// Source is the .clowd file's name, for the generated file's header.
	Source string
	// ProviderVersion pins the provider ("6.14.1"); empty uses
	// ProviderConstraint.
	ProviderVersion string
}

// Result is a lowered program.
type Result struct {
	Config *tfjson.Config
	// Certificates are the addresses of ACM certificates. They must be
	// validated by DNS records the user creates, so the runner creates
	// them first and shows the records before the rest of the apply
	// waits for validation.
	Certificates []string
	Diags        diag.List
}

// Lower turns p into AWS resources.
func Lower(p *ir.Program, opts Options) *Result {
	l := &lowerer{p: p, opts: opts, cfg: &tfjson.Config{}}
	l.provider()
	l.checkNames()
	if l.needsNetwork() {
		l.network()
	}
	if l.has(ir.ServiceKind) {
		l.cfg.DataSource("aws_region", "current", tfjson.Body{})
		l.cfg.Resource("aws_ecs_cluster", "main", tfjson.Body{"name": opts.Project})
	}
	for _, r := range p.Resources {
		switch r := r.(type) {
		case *ir.Service:
			l.service(r)
		case *ir.Database:
			l.database(r)
		case *ir.Bucket:
			l.bucket(r)
		case *ir.Queue:
			l.queue(r)
		case *ir.LoadBalancer:
			l.loadBalancer(r)
		}
	}
	l.overrides()
	l.checkAddresses()
	l.diags.Sort()
	return &Result{Config: l.cfg, Certificates: l.certs, Diags: l.diags}
}

type lowerer struct {
	p     *ir.Program
	opts  Options
	cfg   *tfjson.Config
	diags diag.List
	net   network
	certs []string
}

// network holds references to where things go; each is an Expr when Clowd
// creates the network and a literal when the user brings their own.
type network struct {
	vpc, cidr       any
	public, private any
}

func (l *lowerer) provider() {
	region := ""
	for _, t := range l.p.Targets {
		if t.Cloud == ir.AWS {
			region = t.Region
		}
	}
	// The project's tags go on every resource through the provider's
	// default tags, next to the one Clowd uses to find what it made.
	tagSet := map[string]string{"clowd:project": l.opts.Project}
	for _, t := range l.p.Project.Tags {
		tagSet[t.Key] = t.Value
	}
	conf := tfjson.Body{"default_tags": tfjson.Body{"tags": tagSet}}
	if region != "" {
		conf["region"] = region
	}
	version := ProviderConstraint
	if l.opts.ProviderVersion != "" {
		version = "= " + l.opts.ProviderVersion
	}
	l.cfg.Providers = []tfjson.Provider{{Name: "aws", Source: ProviderSource, Version: version, Config: conf}}
	l.cfg.Comment = fmt.Sprintf("Generated by clowd from %s. Edit that file instead: this one is rewritten on every build.", l.opts.Source)
}

func (l *lowerer) has(k ir.Kind) bool {
	return slices.ContainsFunc(l.p.Resources, func(r ir.Resource) bool { return r.Kind() == k })
}

func (l *lowerer) needsNetwork() bool {
	return l.has(ir.ServiceKind) || l.has(ir.DatabaseKind) || l.has(ir.LoadBalancerKind)
}

// id is a resource's local name in the generated configuration. Clowd
// names are case-insensitive and already valid identifiers.
func id(name string) string { return strings.ToLower(name) }

// physical returns a name for AWS: the project and parts joined by dashes,
// lowercase, with underscores turned into dashes (the strictest services
// allow nothing else). A name longer than max is cut and given a short
// hash of the full name, so it stays unique.
func (l *lowerer) physical(max int, parts ...string) string {
	name := strings.ReplaceAll(strings.ToLower(strings.Join(append([]string{l.opts.Project}, parts...), "-")), "_", "-")
	if len(name) <= max {
		return name
	}
	sum := sha256.Sum256([]byte(name))
	suffix := hex.EncodeToString(sum[:])[:6]
	return strings.TrimRight(name[:max-len(suffix)-1], "-") + "-" + suffix
}

// envPrefix is the prefix of the environment variables a relationship to
// name sets: `db` → DB_HOST, `user-files` → USER_FILES_BUCKET.
func envPrefix(name string) string {
	return strings.ToUpper(strings.ReplaceAll(name, "-", "_"))
}

// checkNames reports resources whose names differ only in `-` versus `_`,
// which AWS would see as the same name.
func (l *lowerer) checkNames() {
	seen := map[string]ir.Resource{}
	for _, r := range l.p.Resources {
		h := r.Meta()
		key := strings.ReplaceAll(id(h.Name), "_", "-")
		if prev, ok := seen[key]; ok {
			l.diags.Add(diag.Errorf(h.Pos, "`%s` and `%s` get the same name on aws, which allows only dashes", prev.Meta().Name, h.Name).
				Suggest("rename one of them"))
			continue
		}
		seen[key] = r
	}
}

// checkAddresses guards against two generated resources sharing an
// address, which contrived names (`web` and `web_80`) could cause.
func (l *lowerer) checkAddresses() {
	seen := map[string]bool{}
	for _, b := range l.cfg.Resources {
		if seen[b.Addr()] {
			l.diags.Add(diag.Errorf(diag.Span{}, "two generated aws resources are both called `%s`", b.Addr()).
				Suggest("rename the resource whose name starts with `%s`", b.Name))
		}
		seen[b.Addr()] = true
	}
}

// ref is shorthand for tfjson.Ref of an attribute of addr.
func ref(addr, attr string) tfjson.Expr { return tfjson.Ref(addr + "." + attr) }

// tags returns a Name tag; the project tag comes from the provider's
// default tags.
func tags(name string) map[string]string { return map[string]string{"Name": name} }

// assumeRole is the trust policy letting service assume a role.
func assumeRole(service string) tfjson.Expr {
	return jsonExpr(map[string]any{
		"Version": "2012-10-17",
		"Statement": []any{map[string]any{
			"Effect":    "Allow",
			"Principal": map[string]any{"Service": service},
			"Action":    "sts:AssumeRole",
		}},
	})
}
