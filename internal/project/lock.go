package project

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/joshjkns/clowd/internal/diag"
)

// Lock is clowd.lock: the provider versions each build pins, so builds are
// reproducible. The CLI writes it after `tofu init` picks versions; users
// commit it and never edit it.
type Lock struct {
	// Providers maps a provider's local name ("aws") to its pin.
	Providers map[string]Provider
}

// Provider is one pinned provider.
type Provider struct {
	// Source is the registry address without the host: "hashicorp/aws".
	Source  string
	Version string
}

// Version returns the pinned version of the provider called name, or "".
func (l Lock) Version(name string) string { return l.Providers[name].Version }

const lockHeader = "# Generated by clowd: provider versions pinned for every build.\n# Commit this file; don't edit it.\n"

// Encode returns l in clowd.lock syntax, with providers sorted by name so
// the file only changes when a pin does.
func (l Lock) Encode() []byte {
	var b strings.Builder
	b.WriteString(lockHeader)
	names := make([]string, 0, len(l.Providers))
	for name := range l.Providers {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		p := l.Providers[name]
		fmt.Fprintf(&b, "\n[providers.%s]\nsource = %s\nversion = %s\n", name, quote(p.Source), quote(p.Version))
	}
	return []byte(b.String())
}

// WriteLock writes l to the project's clowd.lock if it differs from what
// is there, and reports whether it wrote.
func (p *Project) WriteLock(l Lock) (bool, error) {
	path := filepath.Join(p.Root, LockFile)
	data := l.Encode()
	if old, err := os.ReadFile(path); err == nil && string(old) == string(data) {
		return false, nil
	}
	if err := os.WriteFile(path, data, 0o644); err != nil {
		return false, err
	}
	p.Lock = l
	return true, nil
}

func (l *Lock) decode(f *diag.File) diag.List {
	doc, diags := parseTOML(f)
	if diags.HasErrors() {
		return diags
	}
	d := decoder{doc: doc}
	d.keysIn("")
	l.Providers = map[string]Provider{}
	for name, sp := range doc.tables {
		parent, key := splitPath(name)
		if name == "providers" {
			continue
		}
		if parent != "providers" {
			d.add(diag.Errorf(sp, "unknown table `[%s]` in %s", name, LockFile).Suggest("delete %s and run `clowd build` to regenerate it", LockFile))
			continue
		}
		var p Provider
		e := d.keysIn(name, "source", "version")
		if v, ok := e["source"]; ok {
			d.str(v, &p.Source)
		}
		if v, ok := e["version"]; ok {
			d.str(v, &p.Version)
		}
		if p.Source == "" || p.Version == "" {
			d.add(diag.Errorf(sp, "`[%s]` needs a `source` and a `version`", name).Suggest("delete %s and run `clowd build` to regenerate it", LockFile))
			continue
		}
		l.Providers[key] = p
	}
	return d.diags
}

// keysIn is keys for a table whose sub-tables aren't checked.
func (d *decoder) keysIn(path string, known ...string) map[string]entry {
	entries := d.doc.table(path)
	for key, e := range entries {
		if !slices.Contains(known, key) {
			where := LockFile
			if path != "" {
				where = "[" + path + "]"
			}
			d.add(diag.Errorf(e.keyPos, "unknown setting `%s` in %s", key, where))
			delete(entries, key)
		}
	}
	return entries
}

// lockHCLProvider matches a provider block in .terraform.lock.hcl.
var lockHCLProvider = regexp.MustCompile(`^provider\s+"([^"]+)"\s*\{`)

// lockHCLVersion matches its version line.
var lockHCLVersion = regexp.MustCompile(`^version\s*=\s*"([^"]+)"`)

// ReadTofuLock reads the provider versions OpenTofu chose from the
// .terraform.lock.hcl in dir, keyed by source without the registry host
// ("hashicorp/aws"). The file's format is stable and only its provider and
// version lines are needed, so it is scanned rather than parsed as HCL.
func ReadTofuLock(dir string) (map[string]string, error) {
	f, err := os.Open(filepath.Join(dir, ".terraform.lock.hcl"))
	if err != nil {
		return nil, err
	}
	defer f.Close()
	out := map[string]string{}
	var current string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if m := lockHCLProvider.FindStringSubmatch(line); m != nil {
			addr := m[1]
			// registry.opentofu.org/hashicorp/aws → hashicorp/aws
			if parts := strings.Split(addr, "/"); len(parts) == 3 {
				addr = parts[1] + "/" + parts[2]
			}
			current = addr
			continue
		}
		if m := lockHCLVersion.FindStringSubmatch(line); m != nil && current != "" {
			out[current] = m[1]
			current = ""
		}
	}
	return out, sc.Err()
}
