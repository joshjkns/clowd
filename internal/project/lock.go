package project

import (
	"bufio"
	"bytes"
	"encoding/json"
	"errors"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/joshjkns/clowd/internal/diag"
)

// Lock is clowd.lock: the provider versions each build pins, so builds are
// reproducible. The CLI writes it after `tofu init` picks versions; users
// commit it and never edit it, so it is JSON rather than anything meant
// for people to write.
type Lock struct {
	// Providers maps a provider's local name ("aws") to its pin.
	Providers map[string]Provider
}

// Provider is one pinned provider.
type Provider struct {
	// Source is the registry address without the host: "hashicorp/aws".
	Source  string `json:"source"`
	Version string `json:"version"`
}

// Version returns the pinned version of the provider called name, or "".
func (l Lock) Version(name string) string { return l.Providers[name].Version }

const lockComment = "Generated by clowd: provider versions pinned for every build. Commit this file; don't edit it."

// lockFile is the file's layout. The comment comes first, and
// encoding/json sorts the providers by name, so the file only changes
// when a pin does.
type lockFile struct {
	Comment   string              `json:"//"`
	Providers map[string]Provider `json:"providers"`
}

// Encode returns l in clowd.lock syntax.
func (l Lock) Encode() []byte {
	providers := l.Providers
	if providers == nil {
		providers = map[string]Provider{}
	}
	data, err := json.MarshalIndent(lockFile{Comment: lockComment, Providers: providers}, "", "  ")
	if err != nil {
		panic("project: encoding the lock: " + err.Error()) // strings only; can't fail
	}
	return append(data, '\n')
}

// WriteLock writes l to the project's clowd.lock if it differs from what
// is there, and reports whether it wrote.
func (p *Project) WriteLock(l Lock) (bool, error) {
	path := filepath.Join(p.Root, LockFile)
	data := l.Encode()
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) {
		return false, nil
	}
	if err := os.WriteFile(path, data, 0o644); err != nil {
		return false, err
	}
	p.Lock = l
	return true, nil
}

func (l *Lock) decode(f *diag.File) diag.List {
	var diags diag.List
	regenerate := func(sp diag.Span, format string, args ...any) diag.List {
		diags.Add(diag.Errorf(sp, format, args...).Suggest("delete %s and run `clowd build` to regenerate it", LockFile))
		return diags
	}
	dec := json.NewDecoder(strings.NewReader(f.Text))
	dec.DisallowUnknownFields()
	var lf lockFile
	if err := dec.Decode(&lf); err != nil {
		var syn *json.SyntaxError
		var typ *json.UnmarshalTypeError
		switch {
		case errors.As(err, &syn):
			at := int(syn.Offset)
			return regenerate(diag.Span{Start: at, End: at}, "%s is not valid JSON: %v", LockFile, err)
		case errors.As(err, &typ):
			at := int(typ.Offset)
			return regenerate(diag.Span{Start: at, End: at}, "%s has a %s where a %s belongs", LockFile, typ.Value, typ.Type)
		}
		return regenerate(diag.Span{}, "%s is not a lock file: %v", LockFile, err)
	}
	for name, p := range lf.Providers {
		if p.Source == "" || p.Version == "" {
			return regenerate(diag.Span{}, "provider `%s` in %s needs a source and a version", name, LockFile)
		}
	}
	l.Providers = lf.Providers
	return nil
}

// lockHCLProvider matches a provider block in .terraform.lock.hcl.
var lockHCLProvider = regexp.MustCompile(`^provider\s+"([^"]+)"\s*\{`)

// lockHCLVersion matches its version line.
var lockHCLVersion = regexp.MustCompile(`^version\s*=\s*"([^"]+)"`)

// ReadTofuLock reads the provider versions OpenTofu chose from the
// .terraform.lock.hcl in dir, keyed by source without the registry host
// ("hashicorp/aws"). The file's format is stable and only its provider and
// version lines are needed, so it is scanned rather than parsed as HCL.
func ReadTofuLock(dir string) (map[string]string, error) {
	f, err := os.Open(filepath.Join(dir, ".terraform.lock.hcl"))
	if err != nil {
		return nil, err
	}
	defer f.Close()
	out := map[string]string{}
	var current string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if m := lockHCLProvider.FindStringSubmatch(line); m != nil {
			addr := m[1]
			// registry.opentofu.org/hashicorp/aws → hashicorp/aws
			if parts := strings.Split(addr, "/"); len(parts) == 3 {
				addr = parts[1] + "/" + parts[2]
			}
			current = addr
			continue
		}
		if m := lockHCLVersion.FindStringSubmatch(line); m != nil && current != "" {
			out[current] = m[1]
			current = ""
		}
	}
	return out, sc.Err()
}
