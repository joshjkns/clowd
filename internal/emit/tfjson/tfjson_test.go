package tfjson

import (
	"encoding/json"
	"strings"
	"testing"

	"github.com/joshjkns/clowd/internal/golden"
)

func sample() *Config {
	c := &Config{Comment: "Generated by clowd from app.clowd. Do not edit."}
	c.Providers = []Provider{{Name: "aws", Source: "hashicorp/aws", Version: "~> 6.0", Config: Body{"region": "eu-west-2"}}}
	zones := c.DataSource("aws_availability_zones", "available", Body{"state": "available"})
	vpc := c.Resource("aws_vpc", "main", Body{"cidr_block": "10.0.0.0/16", "enable_dns_hostnames": true})
	c.Resource("aws_subnet", "public", Body{
		"count":             2,
		"vpc_id":            Ref(vpc + ".id"),
		"availability_zone": Ref(zones + ".names[count.index]"),
		"tags":              map[string]string{"Name": "shop-public"},
	})
	c.Resource("aws_vpc", "other", Body{"cidr_block": "10.1.0.0/16"})
	c.Resource("aws_ecs_service", "api", Body{
		"load_balancer": []Body{{"container_port": 8080}, {"container_port": 9090}},
		"network_configuration": Body{
			"subnets": Ref("aws_subnet.public[*].id"),
		},
		"depends_on": []string{"aws_lb_listener.web"},
		// User values must survive templating and HTML-ish characters.
		"note": "costs ${5} & <more> %{if}",
	})
	c.EphemeralResource("random_password", "db", Body{"length": 32})
	c.Outputs = []Output{{Name: "web_url", Description: "Where web is served", Value: Expr("http://${aws_lb.web.dns_name}")}}
	return c
}

func TestMarshalGolden(t *testing.T) {
	got, err := Marshal(sample())
	if err != nil {
		t.Fatal(err)
	}
	golden.Check(t, "testdata/sample.golden", string(got))
	var v any
	if err := json.Unmarshal(got, &v); err != nil {
		t.Errorf("output is not JSON: %v", err)
	}
}

func TestMarshalIsDeterministic(t *testing.T) {
	first, _ := Marshal(sample())
	for range 20 {
		if again, _ := Marshal(sample()); string(again) != string(first) {
			t.Fatal("Marshal output changed between runs")
		}
	}
}

func TestEscape(t *testing.T) {
	tests := map[string]string{
		"plain":       "plain",
		"${x}":        "$${x}",
		"%{if a}":     "%%{if a}",
		"$5 and 50%":  "$5 and 50%",
		"already $${": "already $$${",
	}
	for in, want := range tests {
		if got := Escape(in); got != want {
			t.Errorf("Escape(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestMarshalRejectsUnknownTypes(t *testing.T) {
	c := &Config{}
	c.Resource("x", "y", Body{"nested": Body{"bad": struct{}{}}})
	_, err := Marshal(c)
	if err == nil || !strings.Contains(err.Error(), "nested: bad: unsupported value") {
		t.Errorf("Marshal error = %v", err)
	}
}

func TestFind(t *testing.T) {
	c := sample()
	if b := c.Find("aws_vpc.other"); b == nil || b.Body["cidr_block"] != "10.1.0.0/16" {
		t.Errorf("Find(aws_vpc.other) = %v", b)
	}
	if c.Find("aws_vpc.nope") != nil {
		t.Error("Find found a missing resource")
	}
}

func TestJSON(t *testing.T) {
	got, err := JSON(map[string]any{
		"Resource": Ref("aws_s3_bucket.b.arn"),
		"Values":   []any{"a&b", "${not a ref}", 3},
	})
	if err != nil {
		t.Fatal(err)
	}
	want := `{"Resource":"${aws_s3_bucket.b.arn}","Values":["a&b","$${not a ref}",3]}`
	if string(got) != want {
		t.Errorf("JSON =\n%s\nwant\n%s", got, want)
	}
}
